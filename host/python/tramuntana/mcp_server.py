@tool
def connect(
    port: Annotated[Optional[str], Field(description="API port, e.g. /dev/ttyACM1. Omit to autodetect.")] = None,
    serial_number: Annotated[Optional[str], Field(description="USB serial number of the board to use (see list_boards).")] = None,
) -> dict:
    """(Re)connect to a Tramuntana board and return its info. Only needed to
    pick a specific board: every other tool connects automatically."""
    global _want_port, _want_serial
    with _lock:
        _drop()
        _want_port, _want_serial = port, serial_number
        return _run(lambda t: {"port": t.port, **t.info()})



def _png(fig) -> Image:
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=100, bbox_inches="tight")
    import matplotlib.pyplot as plt
    plt.close(fig)
    return Image(data=buf.getvalue(), format="png")


def _pyplot():
    try:
        import matplotlib
    except ImportError:
        raise RuntimeError('matplotlib is missing: install the extra, pip install "tramuntana[mcp]"') from None
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    return plt


def _window(n: int, rate: float, trig: int, t_from_us, t_to_us) -> Tuple[int, int]:
    a = 0 if t_from_us is None else int(trig + t_from_us * 1e-6 * rate)
    b = n if t_to_us is None else int(trig + t_to_us * 1e-6 * rate) + 1
    a, b = max(0, a), min(n, b)
    if b - a < 2:
        raise ValueError("the time window holds less than two samples")
    return a, b


TFrom = Annotated[Optional[float], Field(description="Window start, us from the trigger; omit = capture start.")]

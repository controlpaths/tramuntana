def _describe(name: str, kwargs: dict) -> str:
    args = ", ".join(f"{k}={v!r}" for k, v in kwargs.items() if v is not None)
    text = f"{name}({args})"
    return text if len(text) <= 160 else text[:157] + "..."


def tool(fn):
    """@mcp.tool(), plus: every call of an acting tool is noted on the
    timeline while one is recording, so the agent's own actions show up
    next to their effects."""
    @functools.wraps(fn)
    def wrapper(*args, **kwargs):
        if _timeline is not None and _timeline.running and fn.__name__ not in QUIET_TOOLS:
            _timeline.note(_describe(fn.__name__, kwargs))
        return fn(*args, **kwargs)
    return mcp.tool()(wrapper)


def _on_event(cmd: int, payload: bytes):
    if cmd == P.EVT_EMU:
        _emu_log.append(decode_event(cmd, payload))


def _board() -> Tramuntana:
    """Returns the open board, connecting on first use."""
    global _dev
    if _dev is None:
        _dev = Tramuntana(port=_want_port, serial_number=_want_serial)
        _dev.link.add_listener(_on_event)
    return _dev


def _drop():
    global _dev
    if _timeline is not None and _timeline.running:
        try:
            _timeline.stop()       # entries stay readable; timeline_start again after reconnecting
        except Exception:
            pass
    if _dev is not None:
        try:
            _dev.close()
        except Exception:
            pass
    _dev = None


_I2C_MASTER_CMDS = {P.CMD_I2C_SCAN, P.CMD_I2C_WRITE, P.CMD_I2C_READ, P.CMD_I2C_WRITE_READ,
                    P.CMD_I2C_START, P.CMD_I2C_STOP, P.CMD_I2C_RAW_WRITE, P.CMD_I2C_RAW_READ,
                    P.CMD_I2C_RESET}


def _hint(t: Tramuntana, e: ProtoError) -> str:
    """What a bare status code means for the agent's next step."""
    if t is not None and e.status == 3 and e.cmd in _I2C_MASTER_CMDS:
        # The master released SCL and it never rose (10 ms clock-stretch limit).
        try:
            pullups = t.pullups()
        except Exception:
            pullups = None
        if pullups is False:
            return (" - SCL never went high. The board's I2C pull-ups are off: if the bus has no"
                    " pull-ups of its own, enable them with i2c_config(pullups=True) and retry.")
        return (" - SCL never went high although the pull-ups are on: something holds it low"
                " (a device stretching the clock for > 10 ms, a short, or an unpowered target"
                " clamping the line). Check the levels with dio_read and the target's power.")
    return ""


def _run(fn):
    """Runs fn(board) under the lock, turning library errors into readable ones.
    A link error drops the connection so the next call reconnects (replugged
    board, reflashed firmware...)."""
    with _lock:
        t = None
        try:
            t = _board()
            return fn(t)
        except ProtoError as e:
            raise RuntimeError(f"board rejected the command: {e}{_hint(t, e)}") from None
        except (LinkError, serial.SerialException, OSError) as e:
            _drop()
            raise RuntimeError(f"link error: {e}") from None


def _hex_in(s: str) -> bytes:
    """Parses '9f 00 ff', '9f00ff', '0x9f,0x00', '9f:00' into bytes."""
    out = bytearray()
    for tok in s.replace(",", " ").replace(":", " ").split():
        tok = tok.lower().removeprefix("0x")
        if len(tok) % 2:
            tok = "0" + tok
        out += bytes.fromhex(tok)
    return bytes(out)


def _hex_out(b: bytes) -> str:
    return b.hex(" ")


def _abspath(path: Optional[str]) -> Optional[str]:
    return os.path.abspath(os.path.expanduser(path)) if path else None


def _decimate(values: List[float], max_points: int) -> Tuple[List[float], int]:
    step = max(1, -(-len(values) // max_points))
    return values[::step], step



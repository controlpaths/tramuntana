@tool
def scope_capture(
    n: Annotated[int, Field(ge=16, le=16384, description="Samples per channel (n*channels <= 16384).")] = 1024,
    channels: Annotated[Literal[1, 2], Field(description="1 = AIN0, 2 = AIN0 + AIN1.")] = 1,
    rate_hz: Annotated[Optional[float], Field(gt=0, le=500_000, description=(
        "Sample rate per channel; the aggregate is limited to 500 kS/s. Omit for the maximum."))] = None,
    trigger: Literal["none", "rising", "falling"] = "none",
    level_v: Annotated[float, Field(ge=0, le=3.3, description="Trigger level on AIN0.")] = 1.65,
    pre: Annotated[int, Field(ge=0, description="Samples kept before the trigger.")] = 0,
    timeout_ms: Annotated[int, Field(ge=1, le=60000, description="Give up if no trigger.")] = 5000,
    wait: Annotated[bool, Field(description=(
        "True: wait and return the capture. False: only arm and return at once, so other tools "
        "can stimulate the target (awg_step, dio_write...) before scope_read."))] = True,
    max_points: MaxPoints = 128,
    csv_path: ScopeCsv = None,
) -> dict:
    """Capture AIN0 (and AIN1) with the 12-bit scope, optionally triggered on
    AIN0 with pre-trigger. Returns per-channel stats (min/max/vpp/mean/rms and
    a frequency estimate), measurements (low/high levels, 10-90 % rise and
    fall time, period, duty, overshoot) and a decimated waveform in volts.
    scope_image draws it. If the trigger never comes the result has
    captured=false and state='timeout'."""
    if n * channels > 16384:
        raise ValueError("n * channels must be <= 16384")

    def f(t):
        rate = t.scope.arm(n=n, channels=channels, rate_hz=rate_hz, trigger=trigger,
                           level=level_v, pre=pre, timeout_ms=timeout_ms)
        if not wait:
            return {"state": "armed", "rate_hz": rate, "next": "call scope_read"}
        return _scope_summary(t, timeout_ms / 1000 + 5, max_points, csv_path)
    return _run(f)



"""MCP server exposing the Tramuntana hardware hacking tool to AI agents.

Lets an MCP client (Claude Code, Claude Desktop, Copilot...) drive a
Tramuntana board: target power, SPI/I2C master and sniffers, oscilloscope,
waveform generator, logic analyzer, DIO, ADC and the USB-UART bridge.

It is a thin layer over the rest of this package, so the agent does exactly
what the CLI, the webapp and user scripts do - nothing here talks the
binary protocol by itself.

Needs the [mcp] extra (pip install "tramuntana[mcp]"). Agents launch it over
stdio as `python -m tramuntana.mcp_server` (or the `tramuntana-mcp` script);
`tramuntana ai install <agent>` registers it.
"""


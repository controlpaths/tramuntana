@tool
def i2c_sequence(
    steps: Annotated[List[Dict], Field(description=(
        "Ordered steps. Each is one of: "
        "{'op':'start','address':0x50,'read':false} (START or repeated START + address), "
        "{'op':'write','data':'00 10'}, "
        "{'op':'read','n':4,'nack_last':true}, "
        "{'op':'stop'}."))],
) -> List[dict]:
    """Low-level I2C (I2CDriver style) for sequences a datasheet asks for that
    i2c_write / i2c_write_read can't express. Returns the result of each step;
    a STOP is sent if a step fails with the bus still open."""
    def f(t):
        out = []
        open_bus = False
        try:
            for s in steps:
                op = s.get("op")
                if op == "start":
                    ack = t.i2c.start(int(s["address"]), bool(s.get("read", False)))
                    open_bus = True
                    out.append({"op": "start", "ack": ack})
                elif op == "write":
                    out.append({"op": "write", "acked": t.i2c.raw_write(_hex_in(s["data"]))})
                elif op == "read":
                    rx = t.i2c.raw_read(int(s["n"]), bool(s.get("nack_last", True)))
                    out.append({"op": "read", "data": _hex_out(rx)})
                elif op == "stop":
                    t.i2c.stop()
                    open_bus = False
                    out.append({"op": "stop"})
                else:
                    raise ValueError(f"unknown step {s!r}")
        except Exception:
            if open_bus:
                try:
                    t.i2c.stop()
                except Exception:
                    pass
            raise
        return out
    return _run(f)


@tool
def i2c_bus_reset() -> str:
    """Clock SCL until a stuck slave releases SDA, then send a STOP."""
    return _run(lambda t: (t.i2c.reset_bus(), "bus reset")[1])


# --- sniffers ----------------------------------------------------------------------

@tool
def sniff_start(
    bus: Literal["spi", "i2c"],
    spi_mode: Annotated[Optional[Literal[0, 1, 2, 3]], Field(description="SPI mode of the sniffed bus.")] = None,
    i2c_pullups: Annotated[bool, Field(description="Enable the board's pull-ups while sniffing I2C.")] = False,
) -> str:
    """Start the passive SPI (DIO2..5) or I2C (DIO6/7) sniffer. It only
    listens, so it can watch a target's own master or this board's. Collect
    messages with sniff_read and stop with sniff_stop."""
    def f(t):
        t.link.events.clear()
        if bus == "spi":
            t.spi.sniff(True, spi_mode)
        else:
            t.i2c.sniff(True, i2c_pullups)
        return f"{bus} sniffer on"
    return _run(f)


@tool
def sniff_read(
    duration_s: Annotated[float, Field(ge=0, le=60, description="How long to wait for messages.")] = 1.0,
    max_messages: Annotated[int, Field(ge=1, le=1000)] = 100,
) -> dict:
    """Return the sniffed messages captured so far, waiting up to duration_s
    for more. SPI: MOSI/MISO bytes (first 256 of each message). I2C: frames
    as 'S 50W+ 00+ 10+ P' (+ = ACK, - = NAK)."""
    def f(t):
        msgs = []
        deadline = time.monotonic() + duration_s
        while len(msgs) < max_messages:
            while t.link.events and len(msgs) < max_messages:
                for ev in t.events(timeout=0):
                    if isinstance(ev, SpiMessage):
                        msgs.append({"bus": "spi", "total": ev.total, "mosi": _hex_out(ev.mosi),
                                     "miso": _hex_out(ev.miso), "overrun": ev.overrun})
                    elif isinstance(ev, I2cMessage):
                        msgs.append({"bus": "i2c", "text": str(ev)[4:], "overrun": ev.overrun,
                                     "truncated": ev.truncated})
                    if len(msgs) >= max_messages:
                        break
            if time.monotonic() >= deadline:
                break
            time.sleep(0.02)
        return {"messages": msgs, "count": len(msgs), "pending": len(t.link.events)}
    return _run(f)


@tool
def sniff_stop(bus: Literal["spi", "i2c", "both"] = "both") -> str:
    """Stop the SPI and/or I2C sniffer."""
    def f(t):
        if bus in ("spi", "both"):
            t.spi.sniff(False)
        if bus in ("i2c", "both"):
            t.i2c.sniff(False)
        return f"{bus} sniffer off"
    return _run(f)



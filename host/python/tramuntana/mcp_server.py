# --- sequencer -----------------------------------------------------------------------

STEP_DOC = """Steps, run in order on the board (each a dict with 'op'):
  {'op':'delay_us','us':500}  {'op':'delay_ms','ms':20}
  {'op':'power','on':true}  {'op':'pullups','on':true}
  {'op':'dio_dir','pin':3,'output':true} or {'op':'dio_dir','mask':8,'out_mask':8}
  {'op':'dio_write','pin':3,'level':0} or {'op':'dio_write','mask':8,'value':0}
  {'op':'dio_read'}
  {'op':'wait_dio','pin':0,'level':1,'timeout_us':100000} (or mask/value): records how long it waited
  {'op':'i2c_write','address':0x76,'data':'f4 27'}  {'op':'i2c_read','address':0x76,'n':2}
  {'op':'i2c_write_read','address':0x76,'write':'d0','n':1}
  {'op':'spi_txn','write':'9f','read_n':3}
  {'op':'uart_send','text':'help\\r\\n'} or {'op':'uart_send','hex':'55 aa'} (bridge must be active)
  {'op':'awg_dc','volts':1.2}  {'op':'adc_read','channel':0}
  {'op':'mark','id':1}  {'op':'watch','mask':8}
  {'op':'loop','count':10,'steps':[...]} (one level)
  {'op':'logic_arm', n, rate_hz, trigger, pin, mask, value, pre, timeout_ms} then logic_read afterwards
  {'op':'scope_arm', n, channels, rate_hz, trigger, level, pre, timeout_ms} then scope_read afterwards
Add 'keep_going': true to a step to record its failure and continue."""


def _pin_args(st, mask_key, value_key):
    if "pin" in st:
        pin = int(st["pin"])
        level = st.get("level", st.get("output", 0))
        return 1 << pin, (1 << pin) if level else 0
    return int(st[mask_key]), int(st.get(value_key, 0))


def _build_sequence(steps: List[Dict]) -> Sequence:
    s = Sequence()

    def add(st, in_loop):
        op = st.get("op")
        kg = bool(st.get("keep_going", False))
        if op == "delay_us":
            s.delay_us(int(st["us"]))
        elif op == "delay_ms":
            s.delay_ms(float(st["ms"]))
        elif op == "power":
            s.power(bool(st["on"]))
        elif op == "pullups":
            s.pullups(bool(st["on"]))
        elif op == "dio_dir":
            s.dio_dir(*_pin_args(st, "mask", "out_mask"))
        elif op == "dio_write":
            s.dio_write(*_pin_args(st, "mask", "value"), keep_going=kg)
        elif op == "dio_read":
            s.dio_read()
        elif op == "wait_dio":
            m, v = _pin_args(st, "mask", "value")
            s.wait_dio(m, v, int(st.get("timeout_us", 1_000_000)), keep_going=kg)
        elif op == "i2c_write":
            s.i2c_write(int(st["address"]), _hex_in(st["data"]), keep_going=kg)
        elif op == "i2c_read":
            s.i2c_read(int(st["address"]), int(st["n"]), keep_going=kg)
        elif op == "i2c_write_read":
            s.i2c_write_read(int(st["address"]), _hex_in(st["write"]), int(st["n"]), keep_going=kg)
        elif op == "spi_txn":
            s.spi_txn(_hex_in(st.get("write", "")), int(st.get("read_n", 0)), keep_going=kg)
        elif op == "uart_send":
            data = _hex_in(st["hex"]) if "hex" in st else st["text"].encode().decode("unicode_escape").encode()
            s.uart_send(data, keep_going=kg)
        elif op == "awg_dc":
            s.awg_dc(float(st["volts"]))
        elif op == "adc_read":
            s.adc_read(int(st.get("channel", 0)))
        elif op == "mark":
            s.mark(int(st.get("id", 0)))
        elif op == "watch":
            s.watch(int(st["mask"]))
        elif op == "loop":
            if in_loop:
                raise ValueError("loops don't nest")
            s.loop(int(st["count"]))
            for sub in st.get("steps", []):
                add(sub, True)
            s.end_loop()
        elif op == "logic_arm":
            s.logic_arm(int(st.get("n", 4096)), float(st.get("rate_hz", 10e6)), st.get("trigger", "none"),
                        int(st.get("pin", 0)), int(st.get("mask", 0)), int(st.get("value", 0)),
                        int(st.get("pre", 0)), int(st.get("timeout_ms", 5000)))
        elif op == "scope_arm":
            s.scope_arm(int(st.get("n", 1024)), int(st.get("channels", 1)), st.get("rate_hz"),
                        st.get("trigger", "none"), float(st.get("level", 1.65)), int(st.get("pre", 0)),
                        int(st.get("timeout_ms", 5000)))
        else:
            raise ValueError(f"unknown step op {op!r}")

    for st in steps:
        add(st, False)
    return s


@tool
def sequence_run(
    steps: Annotated[List[Dict], Field(description=STEP_DOC)],
    timeout_s: Annotated[float, Field(gt=0, le=600)] = 10.0,
) -> dict:
    """Run a list of steps on the board itself, with microsecond timing
    between them (a host round trip per tool call is milliseconds). Use it
    for reset/boot sequences, 'release reset then talk to the device
    within N ms', waiting for an IRQ line, pulse trains, or arming a
    capture right before stimulating the target. Returns every executed
    step with its time from the first one (us), result value (levels,
    waited us, volts, bytes read) and status; the run stops at the first
    failing step unless that step has keep_going. Entries also go to the
    timeline when one is recording."""
    s = _build_sequence(steps)

    def f(t):
        r = t.seq.run(s, timeout_s)
        time.sleep(0.05)   # let the run's events (emulator, sniffers, edges) reach the timeline
        out = {"state": r.state, "error": r.error, "steps": []}
        for st in r.steps:
            v = st.value
            if isinstance(v, (bytes, bytearray)):
                v = _hex_out(bytes(v))
            item = {"t_us": st.dt_us, "step": st.label or st.op, "ok": st.ok}
            if not st.ok:
                item["status"] = st.status
            if v is not None:
                item["value"] = v
            out["steps"].append(item)
        if r.state != "done":
            out["stopped_at"] = s.labels.get(r.pc, f"pc {r.pc}")
        return out
    return _run(f)



@tool
def scope_image(t_from_us: TFrom = None, t_to_us: TTo = None) -> Image:
    """PNG plot of the last scope capture (volts vs time from the trigger),
    optionally zoomed into a time window, to look at the shape of a
    waveform: ringing, glitches, slow edges, noise, brown-outs."""
    cap = _last_scope
    if cap is None:
        raise RuntimeError("no scope capture yet: run scope_capture first")
    plt = _pyplot()
    a, b = _window(cap.n, cap.rate_hz, cap.trigger_index, t_from_us, t_to_us)
    ts = [x * 1e6 for x in cap.times()[a:b]]
    fig, ax = plt.subplots(figsize=(10, 4))
    for ch in range(cap.channels):
        ax.plot(ts, cap.volts(ch)[a:b], lw=0.9, label=f"AIN{ch}")
    if a <= cap.trigger_index < b:
        ax.axvline(0, color="grey", ls="--", lw=0.8)
    ax.set_xlabel("us from trigger")
    ax.set_ylabel("V")
    ax.grid(True, alpha=0.3)
    ax.legend(loc="upper right")
    ax.set_title(f"scope {cap.rate_hz / 1e3:g} kS/s, {b - a} samples")
    return _png(fig)



INSTRUCTIONS = """\
Tramuntana is an RP2350-based bench tool for embedded targets, wired to the
target through a 16-pin header (J1):

  J1.1  3V3   switched 3.3 V rail for the target (tool: power)
  J1.3  AIN0  scope ch0 / adc 0      J1.5  AIN1  scope ch1 / adc 1   (0..3.3 V)
  J1.7  AOUT0 waveform generator (PWM + RC filter, 0..3.3 V)
  J1.9  DIO0  UART RX, logic ch0     J1.10 DIO1  UART TX, logic ch1
  J1.11 DIO2  SPI CS,   logic ch2    J1.12 DIO3  SPI MISO, logic ch3
  J1.13 DIO4  SPI MOSI, logic ch4    J1.14 DIO5  SPI SCK,  logic ch5
  J1.15 DIO6  I2C SCL,  logic ch6    J1.16 DIO7  I2C SDA,  logic ch7
  Every DIO is also a plain GPIO. UART: DIO1 -> target RX, DIO0 <- target TX.

Conventions: byte strings are hex ("9f 00 ff", "9f00ff" or "0x9f,0x00");
I2C addresses are 7-bit integers; voltages in volts; frequencies in Hz.
The connection is opened automatically on the first tool call; use
list_boards / connect only when several boards are plugged in.
Sniffers and the logic analyzer only listen, so they can watch traffic
generated by this same board (e.g. run logic_capture while doing I2C).
While the UART bridge port is open, DIO0/DIO1 belong to the UART and GPIO
use of them fails with 'busy'; SPI and I2C keep working alongside. Typical bring-up: power(on) -> i2c_scan /
spi_transaction to identify the target -> scope/logic to check signals.
Captures are analysed on the host: scope results carry measurements (levels,
rise/fall time, frequency, duty, overshoot); logic captures can be decoded as
UART/I2C/SPI (decode= on logic_capture, or logic_decode to re-decode the last
capture with other pins/baud/mode without capturing again). scope_image and
logic_image return a PNG of the last capture to look at the waveform.

Debugging over time: timeline_start records, on one clock, the target's UART
output, sniffed I2C/SPI messages, edges on watched DIOs (reset, IRQ, LEDs),
transfers with an emulated device, sequencer runs and every action taken
through these tools; timeline_read shows a window of it, so cause and effect
line up ("the sensor NAKed 3 ms after reset, then the firmware printed
'not found'").
sequence_run executes a list of steps on the board itself with microsecond
timing (reset pulses, wait for a pin, bus transfers, delays, arming captures)
- use it whenever timing between steps matters; separate tool calls are
milliseconds to seconds apart.
emu_i2c / emu_spi make the board answer as a device on the target's bus,
from a 256-byte register file: test a firmware against a sensor returning any
value, or missing (emu_stop).
uart_ctrl maps the bridge port's RTS/DTR to two DIOs (reset/boot), so
esptool (and tools that reset a target the same way) can reset and flash it
through the bridge; uart_set_lines drives them from here.
"""


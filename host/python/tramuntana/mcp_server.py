# --- logic analyzer ----------------------------------------------------------------

def _logic_channel(cap, dio: int, max_edges: int) -> dict:
    bits = cap.channel(dio)
    edges = cap.edges(dio)
    rising = [i for i, lvl in edges if lvl == 1]
    out = {"initial": bits[0] if bits else None, "final": bits[-1] if bits else None,
           "edges": len(edges), "high_fraction": round(sum(bits) / len(bits), 4) if bits else None}
    if len(rising) >= 2:
        out["freq_hz"] = round(cap.rate_hz * (len(rising) - 1) / (rising[-1] - rising[0]), 3)
    if max_edges and edges:
        us = 1e6 / cap.rate_hz
        out["first_edges"] = [{"t_us": round((i - cap.trigger_index) * us, 4),
                               "level": lvl} for i, lvl in edges[:max_edges]]
    return out


def _unexpected_nak(f) -> bool:
    """A NAK on the address or on a written byte; the master NAKs the last
    byte of a read on purpose."""
    data = f.data[:-1] if f.read else f.data
    return f.ack is False or any(not a for _, a in data)


def _decode(cap, protocol: str, max_items: int, pin: Optional[int] = None, baud: Optional[int] = None,
            parity: str = "none", stop_bits: int = 1, scl: int = 6, sda: int = 7,
            cs: Optional[int] = 2, sck: int = 5, mosi: Optional[int] = 4, miso: Optional[int] = 3,
            spi_mode: int = 0, lsb_first: bool = False) -> dict:
    """Decodes a logic capture; defaults follow the J1 pinout."""
    if protocol == "uart":
        pin = 0 if pin is None else pin
        guessed = baud is None
        if guessed:
            baud = decode.guess_baud(cap, pin)
            if baud is None:
                return {"protocol": "uart", "pin": pin, "error": f"too few edges on DIO{pin} to guess the baud rate"}
        frames = decode.uart(cap, pin, baud, parity=parity, stop_bits=stop_bits)
        out = {"protocol": "uart", "pin": pin, "baud": baud, "baud_guessed": guessed,
               "count": len(frames), "text": decode.uart_text(frames[:max_items]),
               "parity_errors": sum(f.parity_error for f in frames),
               "framing_errors": sum(f.framing_error for f in frames)}
        if out["framing_errors"]:
            out["hint"] = "framing errors usually mean a wrong baud rate or framing, or a break"
        if frames:
            out["first_s"], out["last_s"] = frames[0].t_s, frames[-1].t_s
        return out
    if protocol == "i2c":
        tr = decode.i2c(cap, scl, sda)
        return {"protocol": "i2c", "scl": scl, "sda": sda, "count": len(tr),
                "with_nak": sum(any(_unexpected_nak(f) for f in x.message.frames) for x in tr),
                "transfers": [{"t_us": round(x.t_s * 1e6, 3), "text": str(x).split("us ", 1)[1],
                               "scl_hz": x.scl_hz} for x in tr[:max_items]]}
    tr = decode.spi(cap, cs, sck, mosi, miso, spi_mode, lsb_first)
    return {"protocol": "spi", "cs": cs, "sck": sck, "mosi": mosi, "miso": miso, "mode": spi_mode,
            "count": len(tr),
            "transfers": [{"t_us": round(x.t_s * 1e6, 3), "mosi": _hex_out(bytes(x.mosi)),
                           "miso": _hex_out(bytes(x.miso)), "sck_hz": x.sck_hz,
                           **({"partial_bits": x.partial_bits} if x.partial_bits else {}),
                           **({} if x.complete else {"cut": True})} for x in tr[:max_items]]}


def _logic_summary(t, wait_s: float, channels, max_edges: int, vcd_path, csv_path, names,
                   protocol: Optional[str] = None, max_items: int = 50) -> dict:
    global _last_logic
    st = _wait_capture(t.logic, wait_s)
    if st["state"] != "done":
        return _not_done(st)
    cap = _last_logic = t.logic.read()
    out = {"state": "done", "captured": True, "rate_hz": cap.rate_hz, "n": cap.n,
           "trigger_index": cap.trigger_index, "duration_s": cap.n / cap.rate_hz, "channels": {}}
    for dio in (channels if channels is not None else range(8)):
        out["channels"][f"DIO{dio}"] = _logic_channel(cap, dio, max_edges)
    if vcd_path:
        cap.to_vcd(_abspath(vcd_path), names)
        out["vcd"] = _abspath(vcd_path)
    if csv_path:
        cap.to_csv(_abspath(csv_path))
        out["csv"] = _abspath(csv_path)
    if protocol:
        out["decoded"] = _decode(cap, protocol, max_items)
    return out



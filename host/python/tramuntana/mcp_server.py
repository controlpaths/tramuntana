NO_CAPTURE_HINT = {
    "armed": "still waiting for the trigger: call the *_read tool again, or it times out",
    "running": "still capturing: call the *_read tool again",
    "timeout": "the trigger condition never happened within timeout_ms",
    "aborted": "the capture was aborted",
    "idle": "nothing armed",
}


def _wait_capture(inst, wait_s: float) -> dict:
    """Waits for a capture to leave armed/running. A missing trigger is a
    result for the agent, not an error, so this never raises for it."""
    try:
        return inst.wait(timeout=wait_s)
    except LinkError:
        return inst.status()      # still armed/running after wait_s


def _not_done(st: dict) -> dict:
    return {"state": st["state"], "captured": False, "hint": NO_CAPTURE_HINT.get(st["state"], "")}


def _round(d: dict) -> dict:
    return {k: (float(f"{v:.4g}") if isinstance(v, float) else v) for k, v in d.items()}


def _scope_summary(t, wait_s: float, max_points: int, csv_path: Optional[str]) -> dict:
    global _last_scope
    st = _wait_capture(t.scope, wait_s)
    if st["state"] != "done":
        return _not_done(st)
    cap = _last_scope = t.scope.read()
    out = {"state": "done", "captured": True, "rate_hz": cap.rate_hz, "n": cap.n,
           "trigger_index": cap.trigger_index, "duration_s": cap.n / cap.rate_hz, "channels": {}}
    for ch in range(cap.channels):
        st = {k: (round(v, 4) if isinstance(v, float) else v) for k, v in cap.stats(ch).items()}
        entry = {"stats": st, "measure": _round(decode.measure(cap, ch))}
        if max_points:
            pts, step = _decimate([round(v, 3) for v in cap.volts(ch)], max_points)
            entry.update({"volts": pts, "point_spacing_s": step / cap.rate_hz})
        out["channels"][f"AIN{ch}"] = entry
    if max_points:
        out["t0_s"] = -cap.trigger_index / cap.rate_hz
    if csv_path:
        cap.to_csv(_abspath(csv_path))
        out["csv"] = _abspath(csv_path)
    return out



#!/usr/bin/env python3
"""
Convert every image dropped in this folder into a C header of RGB565 pixel
data, for the ST7735R display on Tramuntana Lite r1a (see
fw/boards/tramuntana_lite_r1a-common.dtsi).

Generic and re-runnable: add any .png/.jpg/.jpeg/.bmp/.gif here, re-run this
script, and it shows up in fw/imgs/images_gen.h as one more entry in
tramuntana_images[] - no per-image code needed on the firmware side.

Each image is cropped-to-fill (not stretched) to the target size, so a
source with a different aspect ratio than the display just loses its edges
instead of getting distorted.

Every image also gets rotated by DEFAULT_ROTATE degrees before that, to
match how the ST7735R panel sits on the board (it's mounted upside down
relative to a "natural" image orientation) - override per run with
--rotate if a specific source is already oriented for the panel.

Usage:
    python3 convert_images.py [--width 128] [--height 160] [--rotate 180]
"""
import argparse
import re
from pathlib import Path

from PIL import Image, ImageOps

SCRIPT_DIR = Path(__file__).resolve().parent
OUTPUT_HEADER = SCRIPT_DIR / "images_gen.h"
IMAGE_EXTENSIONS = {".png", ".jpg", ".jpeg", ".bmp", ".gif"}
# The panel is mounted upside down on the board, so every source image
# needs this rotation to come out right side up on screen.
DEFAULT_ROTATE = 180
ROTATE_TRANSPOSE = {
    0: None,
    90: Image.Transpose.ROTATE_270,
    180: Image.Transpose.ROTATE_180,
    270: Image.Transpose.ROTATE_90,
}


def c_identifier(stem):
    """Turn a filename stem into a valid, unique-enough C identifier."""
    ident = re.sub(r"[^0-9a-zA-Z_]", "_", stem.lower())
    if not ident or ident[0].isdigit():
        ident = "_" + ident
    return ident


def to_rgb565_bytes(im):
    """Big-endian RGB565 bytes - the wire order zephyr,mipi-dbi-spi expects,
    matching colmod = <0x55> in the display devicetree node."""
    out = bytearray()
    for r, g, b in im.getdata():
        value = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        out += value.to_bytes(2, "big")
    return bytes(out)


def format_c_array(name, data):
    lines = [f"static const uint8_t {name}_pixels[] = {{"]
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("  " + " ".join(f"0x{b:02x}," for b in chunk))
    lines.append("};")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                      formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--width", type=int, default=128, help="display width in pixels")
    parser.add_argument("--height", type=int, default=160, help="display height in pixels")
    parser.add_argument("--rotate", type=int, default=DEFAULT_ROTATE, choices=sorted(ROTATE_TRANSPOSE),
                         help=f"clockwise rotation applied to every image (default: {DEFAULT_ROTATE})")
    args = parser.parse_args()

    images = sorted(p for p in SCRIPT_DIR.iterdir() if p.suffix.lower() in IMAGE_EXTENSIONS)
    if not images:
        print(f"No images found in {SCRIPT_DIR}")
        return

    arrays = []
    entries = []
    seen_names = set()
    for path in images:
        name = c_identifier(path.stem)
        if name in seen_names:
            raise SystemExit(f"Two images map to the same identifier '{name}': "
                              f"rename one of them")
        seen_names.add(name)

        im = Image.open(path).convert("RGB")
        transpose = ROTATE_TRANSPOSE[args.rotate]
        if transpose is not None:
            im = im.transpose(transpose)
        im = ImageOps.fit(im, (args.width, args.height), Image.LANCZOS)
        data = to_rgb565_bytes(im)

        arrays.append(format_c_array(name, data))
        entries.append(
            f'  {{ "{path.stem}", {args.width}, {args.height}, '
            f"{name}_pixels, sizeof({name}_pixels) }},"
        )
        print(f"{path.name}: {args.width}x{args.height}, {len(data)} bytes -> {name}_pixels")

    header = [
        "/*",
        " * Auto-generated by fw/imgs/convert_images.py - do not edit by hand.",
        f" * Source images: {', '.join(p.name for p in images)}",
        " */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "",
        "struct tramuntana_image {",
        "  const char *name;",
        "  uint16_t width;",
        "  uint16_t height;",
        "  const uint8_t *pixels; /* RGB565, big-endian */",
        "  size_t pixels_len;",
        "};",
        "",
        *arrays,
        "",
        "static const struct tramuntana_image tramuntana_images[] = {",
        *entries,
        "};",
        "",
        "#define TRAMUNTANA_IMAGE_COUNT (sizeof(tramuntana_images) / "
        "sizeof(tramuntana_images[0]))",
        "",
    ]

    OUTPUT_HEADER.write_text("\n".join(header))
    print(f"\nWrote {OUTPUT_HEADER} ({OUTPUT_HEADER.stat().st_size} bytes)")


if __name__ == "__main__":
    main()

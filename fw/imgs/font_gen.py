#!/usr/bin/env python3
"""
Rasterizes DejaVu Sans Mono (regular and bold) into a C header of packed
1bpp glyphs, for drawing text straight into an RGB565 framebuffer on the
ST7735R display (fw/apps/tramuntana_fw/src/display.c,
display_draw_string() / display_draw_string_bold()).

Why a real TrueType face and not PIL's built-in default font: since Pillow
10 load_default() is itself a TrueType font (Aileron) drawn anti-aliased,
and thresholding that at 11px lost whole strokes - the 'O' came out as a
'C'. DejaVu Sans Mono at 11px is hinted for exactly this kind of size and
survives a plain threshold cleanly; its Bold weight gives a proper bold
face for the screen titles instead of a smeared double-draw.

Glyphs are trimmed to their ink horizontally (so the table is effectively
proportional - 'I' and '.' don't take a full monospace cell) and packed
LSB = leftmost column; the drawing code advances by width + 1.

Generic and re-runnable, same spirit as convert_images.py: re-run this if
the character set or vertical window below needs to change, no other code
changes needed - display_draw_char() just indexes the tables by codepoint.

Usage:
    python3 font_gen.py
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

SCRIPT_DIR = Path(__file__).resolve().parent
OUTPUT_HEADER = SCRIPT_DIR / "font_gen.h"

FONT_DIR = Path("/usr/share/fonts/truetype/dejavu")
FACES = {
    "font_glyphs": FONT_DIR / "DejaVuSansMono.ttf",
    "font_glyphs_bold": FONT_DIR / "DejaVuSansMono-Bold.ttf",
}
FONT_SIZE = 11
THRESHOLD = 110     # anti-aliased coverage (0-255) that counts as ink

FIRST_CHAR = 0x20   # ' '
LAST_CHAR = 0x7e    # '~'
# Vertical ink window shared by every glyph (so baselines line up). At 11px
# DejaVu Sans Mono puts capitals on rows 3..10 and descenders on 11..13;
# this keeps the caps plus two rows of descender, cropping the last row of
# 'g'/'y'/'p' - tramuntana_fw only draws uppercase, digits and
# punctuation anyway.
ROW_Y0 = 2
ROW_Y1 = 13
CANVAS = (24, 24)
SPACE_WIDTH = 3     # ' ' has no ink; give it a sensible advance
EMPTY_WIDTH = 3     # any other inkless glyph


def rasterize(face_path):
    font = ImageFont.truetype(str(face_path), FONT_SIZE)
    glyphs = []

    for code in range(FIRST_CHAR, LAST_CHAR + 1):
        ch = chr(code)
        im = Image.new("L", CANVAS, 0)
        ImageDraw.Draw(im).text((0, 0), ch, fill=255, font=font)

        raw_rows = []
        for y in range(ROW_Y0, ROW_Y1):
            bits = 0
            for x in range(CANVAS[0]):
                if im.getpixel((x, y)) >= THRESHOLD:
                    bits |= 1 << x
            raw_rows.append(bits)

        ink = [r for r in raw_rows if r]
        if not ink:
            width = SPACE_WIDTH if ch == " " else EMPTY_WIDTH
            rows = [0] * len(raw_rows)
        else:
            union = 0
            for r in ink:
                union |= r
            left = (union & -union).bit_length() - 1   # lowest set bit
            width = union.bit_length() - left
            rows = [r >> left for r in raw_rows]
        glyphs.append((width, rows))

    return glyphs


def main():
    tables = {name: rasterize(path) for name, path in FACES.items()}
    height = ROW_Y1 - ROW_Y0
    max_width = max(w for glyphs in tables.values() for w, _ in glyphs)
    assert max_width <= 16, "rows are uint16_t"

    lines = [
        "/*",
        " * Auto-generated by fw/imgs/font_gen.py - do not edit by hand.",
        f" * DejaVu Sans Mono {FONT_SIZE}px (regular + bold), rasterized to packed 1bpp",
        " * glyphs, trimmed to their ink horizontally.",
        " */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"#define FONT_FIRST_CHAR {FIRST_CHAR}",
        f"#define FONT_LAST_CHAR  {LAST_CHAR}",
        f"#define FONT_HEIGHT     {height}",
        f"#define FONT_MAX_WIDTH  {max_width}",
        "",
        "struct font_glyph {",
        "  uint8_t width;             /* visible columns, <= FONT_MAX_WIDTH */",
        "  uint16_t rows[FONT_HEIGHT]; /* one bit per column, LSB = leftmost */",
        "};",
    ]

    for name, glyphs in tables.items():
        lines += [
            "",
            f"static const struct font_glyph {name}"
            "[FONT_LAST_CHAR - FONT_FIRST_CHAR + 1] = {",
        ]
        for code, (width, rows) in zip(range(FIRST_CHAR, LAST_CHAR + 1), glyphs):
            row_str = ", ".join(f"0x{r:04x}" for r in rows)
            lines.append(f"  {{ {width}, {{ {row_str} }} }}, /* '{chr(code)}' */")
        lines.append("};")
    lines.append("")

    OUTPUT_HEADER.write_text("\n".join(lines))
    print(f"Wrote {OUTPUT_HEADER} ({OUTPUT_HEADER.stat().st_size} bytes), "
          f"{len(tables)} faces x {LAST_CHAR - FIRST_CHAR + 1} glyphs, "
          f"{max_width}x{height} max cell")


if __name__ == "__main__":
    main()
